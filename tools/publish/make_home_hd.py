r"""The browser HOME's high-resolution appearance (Preview for: Browser HOME): the same high-resolution HOME files the computer's game
window uses (tools/companion/native_home/hd_sprites.py: each theme's overlays redrawn at twice their stage size, the background picture at
2x with its painted panels redrawn while the picture itself stays the approved retro art, the theme picker previews) written once into
tools/publish/assets/home/hd/ for the website and the Windows bundle, with a manifest (home-hd.json) the page reads. The console's own
packages never use these files. Run after a change to hd_sprites.py, home-art.json or a theme's approved art:
  python tools/publish/make_home_hd.py            (needs Pillow; writes only tools/publish/assets/home/hd/)"""
from __future__ import annotations
import hashlib, json, os, shutil, sys
HERE = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(REPO, "tools", "companion"))
from PIL import Image
from native_home import hd_sprites as HDS
from native_home.package import THEMES
HOME = os.path.join(HERE, "assets", "home"); OUT = os.path.join(HOME, "hd")
FONTS = os.path.join(REPO, "tools", "companion", "native_home", "fonts")

def sha(p: str) -> str: return hashlib.sha256(open(p, "rb").read()).hexdigest()

def main() -> int:
    art = json.load(open(os.path.join(HOME, "home-art.json"), encoding="utf-8"))
    if os.path.isdir(OUT): shutil.rmtree(OUT)
    os.makedirs(OUT); os.makedirs(os.path.join(OUT, "fonts"))
    man: dict = {"schema": "ccs-home-hd/1", "drawing": HDS.VERSION, "note": "generated by tools/publish/make_home_hd.py from home-art.json and native_home/hd_sprites.py", "themes": {}, "fonts": {}}
    for tid, th in THEMES.items():
        T = art["themes"][tid]; rec: dict = {"sprites": {}}
        with Image.open(os.path.join(HOME, th["scene"])) as im: scene2 = HDS.scene_hd(tid, im, T["geometry"])
        if scene2 is not None:
            f = f"scene-{tid}-2x.png"; scene2.save(os.path.join(OUT, f), "PNG", optimize=True); rec["scene_2x"] = f
            f = f"thumb-{tid}-2x.jpg"; scene2.convert("RGB").resize((640, 360), Image.LANCZOS).save(os.path.join(OUT, f), "JPEG", quality=90, optimize=True); rec["thumb_2x"] = f
        for name, sp in T["sprites"].items():   # every sprite the website or the native renderer may draw
            if not HDS.has(tid, name): continue
            with Image.open(os.path.join(HOME, sp["file"])) as im: hi = HDS.render(tid, name, im.convert("RGBA"))
            if hi is None: continue
            f = f"sprite-{tid}-{name}-2x.png"; hi.save(os.path.join(OUT, f), "PNG", optimize=True); rec["sprites"][name] = f
        man["themes"][tid] = rec
    for f in sorted(os.listdir(FONTS)):   # the high-resolution text faces (Barlow, SIL Open Font License) and their license
        if f.lower().endswith((".ttf", ".txt")) or "ofl" in f.lower(): shutil.copy2(os.path.join(FONTS, f), os.path.join(OUT, "fonts", f)); man["fonts"][f] = "fonts/" + f
    man["files"] = {f: sha(os.path.join(OUT, f)) for f in sorted(os.listdir(OUT)) if os.path.isfile(os.path.join(OUT, f))}
    json.dump(man, open(os.path.join(HOME, "home-hd.json"), "w", encoding="utf-8", newline="\n"), indent=1, sort_keys=True)
    n = sum(len(t["sprites"]) for t in man["themes"].values()); size = sum(os.path.getsize(os.path.join(dp, f)) for dp, _, fs in os.walk(OUT) for f in fs)
    print(f"home-hd.json: {len(man['themes'])} themes, {n} redrawn overlays, {sum(1 for t in man['themes'].values() if t.get('scene_2x'))} scenes, {len(man['fonts'])} font files, {size / 1e6:.1f} MB")
    return 0

if __name__ == "__main__": sys.exit(main())
