    public static class PinnedDriver
    {
        public const ushort Vid = 0x1F3A, Pid = 0xEFE8;
        public const string HardwareId = @"USB\VID_1F3A&PID_EFE8";
        public const string InterfaceGuid = "{409ADFB6-9503-4D0B-BDDF-C2BD419E0F60}";
        public const string InfName = "nintendo_classic.inf";
        public const string Provider = "libwdi";
        public const string Service = "WinUSB";
        public const string ClassGuid = "{88BAE032-5A81-49F0-BC3D-A4FF138216D6}";
        public const string CertificateSubject = @"CN=USB\VID_1F3A&PID_EFE8 (libwdi autogenerated)";
        public const string CertificateFriendlyName = "libwdi";
        public const string HelperFile = @"driver\classic_driver.exe";
        public const string HelperSha256 = "88a2c6bc3e296c81ca3544557a2e254e894c867ceb0d60e14c2fc2e5d610462d";
        public const string HelperSource = "TeamShinkansen/libwdi tag classic_driver_1 = 6d379a32e93e8a8f27e6205cf2c45d26ab98a68d (examples/classic-driver.c)";
        /// <summary>the package the pinned setup creates: libwdi's WinUSB INF named nintendo_classic.inf with the pinned interface GUID</summary>
        public static bool IsPinned(DriverPackage p) => p != null && !p.IsInbox && Eq(p.OriginalName, InfName) && Eq(p.Provider, Provider)
            && p.InterfaceGuids.Any(g => Eq(g, InterfaceGuid)) && p.Services.Any(s => Eq(s, Service));
        internal static bool Eq(string a, string b) => string.Equals(a ?? "", b ?? "", StringComparison.OrdinalIgnoreCase);
    }

    public enum CertStore { Root, TrustedPublisher }

    public static class UsbId
    {
        public static string Of(ushort vid, ushort pid) => string.Format(CultureInfo.InvariantCulture, @"USB\VID_{0:X4}&PID_{1:X4}", vid, pid);
        /// <summary>USB\VID_vvvv&amp;PID_pppp itself or with a suffix (&amp;REV_, &amp;MI_), never a longer PID or another identity</summary>
        public static bool Matches(string id, ushort vid, ushort pid)
        {
            if (id == null) return false; var b = Of(vid, pid);
            return id.StartsWith(b, StringComparison.OrdinalIgnoreCase) && (id.Length == b.Length || id[b.Length] == '&');
        }
        static readonly Regex published = new Regex(@"^oem[0-9]{1,6}\.inf$", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);
        /// <summary>a third-party package's published name (oemNN.inf): the only kind of name a removal can ever name</summary>
        public static bool IsPublishedName(string name) => name != null && published.IsMatch(name);
        public static bool IsThumbprint(string t) => t != null && t.Length == 40 && t.All(c => c >= '0' && c <= '9' || c >= 'A' && c <= 'F');
        public static string NormThumbprint(string t) => (t ?? "").Replace(" ", "").ToUpperInvariant();
    }

    public sealed class DeviceBinding
    {
        public string InstanceId;                         // USB\VID_1F3A&PID_EFE8\5&...
        public List<string> HardwareIds = new List<string>();
        public bool Present;                              // connected now
        public string Service;                            // "WinUSB", "libusb0", "libusbK", ... ; "" when no driver is bound
        public string InfPath;                            // the bound package: oemNN.inf, or an inbox INF such as winusb.inf; "" when none
        public string Provider, DriverVersion;
        public List<string> InterfaceGuids = new List<string>();   // Device Parameters\DeviceInterfaceGUIDs (what the WinUSB transport looks for)
        public int ProblemCode;
        public bool NeedsRestart;                         // Windows marked this device as waiting for a restart
        public bool Bound => !string.IsNullOrEmpty(Service) || !string.IsNullOrEmpty(InfPath);

        public JObj ToJson() => new JObj { { "instance_id", InstanceId }, { "hardware_ids", HardwareIds }, { "present", Present }, { "service", Service ?? "" },
            { "inf", InfPath ?? "" }, { "provider", Provider ?? "" }, { "driver_version", DriverVersion ?? "" }, { "interface_guids", InterfaceGuids },
            { "problem_code", ProblemCode }, { "needs_restart", NeedsRestart } };
        public static DeviceBinding From(Dictionary<string, object> d) => d == null ? null : new DeviceBinding
        {
            InstanceId = d.S("instance_id"), HardwareIds = Strs(d.A("hardware_ids")), Present = d.B("present"), Service = d.S("service") ?? "", InfPath = d.S("inf") ?? "",
            Provider = d.S("provider") ?? "", DriverVersion = d.S("driver_version") ?? "", InterfaceGuids = Strs(d.A("interface_guids")), ProblemCode = (int)d.L("problem_code", 0), NeedsRestart = d.B("needs_restart"),
        };
        public DeviceBinding Copy() => From(Json.Parse(Json.Write(ToJson())));
        internal static List<string> Strs(List<object> a) => a == null ? new List<string>() : a.OfType<string>().ToList();
    }

    public sealed class DriverPackage
    {
        public string PublishedName;                      // oemNN.inf; for an inbox package its own name (winusb.inf)
        public string OriginalName;                       // nintendo_classic.inf
        public string Provider, ClassGuid, DriverVersion;
        public List<string> DeclaredIds = new List<string>();      // USB identities its INF names
        public List<string> InterfaceGuids = new List<string>();   // DeviceInterfaceGUIDs its INF writes
        public List<string> Services = new List<string>();         // AddService names in its INF
        public string InfSha256, CatalogName, CatalogSha256;
        public string SignerSubject, SignerThumbprint;    // the catalog's signer certificate (read from the catalog; not a trust decision)
        public bool PendingRemoval;                       // a removal Windows has not finished (waits for a restart)
        public bool IsInbox => !UsbId.IsPublishedName(PublishedName);

        public JObj ToJson() => new JObj { { "published_name", PublishedName }, { "original_name", OriginalName ?? "" }, { "provider", Provider ?? "" }, { "class_guid", ClassGuid ?? "" },
            { "driver_version", DriverVersion ?? "" }, { "declared_ids", DeclaredIds }, { "interface_guids", InterfaceGuids }, { "services", Services }, { "inf_sha256", InfSha256 ?? "" },
            { "catalog", CatalogName ?? "" }, { "catalog_sha256", CatalogSha256 ?? "" }, { "signer_subject", SignerSubject ?? "" }, { "signer_thumbprint", SignerThumbprint ?? "" },
            { "pending_removal", PendingRemoval }, { "inbox", IsInbox } };
        public static DriverPackage From(Dictionary<string, object> d) => d == null ? null : new DriverPackage
        {
            PublishedName = d.S("published_name"), OriginalName = d.S("original_name") ?? "", Provider = d.S("provider") ?? "", ClassGuid = d.S("class_guid") ?? "", DriverVersion = d.S("driver_version") ?? "",
            DeclaredIds = DeviceBinding.Strs(d.A("declared_ids")), InterfaceGuids = DeviceBinding.Strs(d.A("interface_guids")), Services = DeviceBinding.Strs(d.A("services")),
            InfSha256 = d.S("inf_sha256") ?? "", CatalogName = d.S("catalog") ?? "", CatalogSha256 = d.S("catalog_sha256") ?? "", SignerSubject = d.S("signer_subject") ?? "",
            SignerThumbprint = d.S("signer_thumbprint") ?? "", PendingRemoval = d.B("pending_removal"),
        };
        public DriverPackage Copy() => From(Json.Parse(Json.Write(ToJson())));
        /// <summary>the same bytes and identity as another reading of it (a changed package is never treated as ours)</summary>
        public bool SameContent(DriverPackage o) => o != null && PinnedDriver.Eq(PublishedName, o.PublishedName) && PinnedDriver.Eq(OriginalName, o.OriginalName)
            && PinnedDriver.Eq(InfSha256, o.InfSha256) && PinnedDriver.Eq(CatalogSha256, o.CatalogSha256) && PinnedDriver.Eq(SignerThumbprint, o.SignerThumbprint)
            && !string.IsNullOrEmpty(InfSha256) && !string.IsNullOrEmpty(CatalogSha256);
    }

    public sealed class CertificateEntry
    {
        public CertStore Store;
        public string Thumbprint, Subject, FriendlyName, NotAfterUtc;
        public bool HasPrivateKey;
        public JObj ToJson() => new JObj { { "store", Store.ToString() }, { "thumbprint", Thumbprint }, { "subject", Subject ?? "" }, { "friendly_name", FriendlyName ?? "" },
            { "not_after_utc", NotAfterUtc ?? "" }, { "has_private_key", HasPrivateKey } };
        public static CertificateEntry From(Dictionary<string, object> d) => d == null ? null : new CertificateEntry
        {
            Store = d.S("store") == "TrustedPublisher" ? CertStore.TrustedPublisher : CertStore.Root, Thumbprint = d.S("thumbprint"), Subject = d.S("subject") ?? "",
            FriendlyName = d.S("friendly_name") ?? "", NotAfterUtc = d.S("not_after_utc") ?? "", HasPrivateKey = d.B("has_private_key"),
        };
        public bool SameAs(CertificateEntry o) => o != null && o.Store == Store && PinnedDriver.Eq(o.Thumbprint, Thumbprint) && PinnedDriver.Eq(o.Subject, Subject)
            && PinnedDriver.Eq(o.NotAfterUtc, NotAfterUtc) && o.HasPrivateKey == HasPrivateKey;
        public string Key => Store + ":" + UsbId.NormThumbprint(Thumbprint);
    }

    public sealed class RestartState
    {
        public bool SystemPending;                        // Windows itself is waiting for a restart (any reason)
        public List<string> Reasons = new List<string>();
        public string BootUtc;                            // when Windows last started (now less the time since it started); null when unknown
        public JObj ToJson() => new JObj { { "system_pending", SystemPending }, { "reasons", Reasons }, { "boot_utc", BootUtc } };
        public static RestartState From(Dictionary<string, object> d) => d == null ? new RestartState() : new RestartState { SystemPending = d.B("system_pending"), Reasons = DeviceBinding.Strs(d.A("reasons")), BootUtc = d.S("boot_utc") };

        /// <summary>Windows has started again since the moment afterUtc: this reading's start time is later than that moment and is not the
        /// start time read then (bootThenUtc) moved by a clock adjustment. False whenever either time is unknown.</summary>
        public static bool RestartedSince(RestartState now, string afterUtc, string bootThenUtc)
        {
            if (!Utc(now?.BootUtc, out var boot) || !Utc(afterUtc, out var after) || boot <= after) return false;
            return !Utc(bootThenUtc, out var then) || Math.Abs((boot - then).TotalSeconds) > 120;
        }
        static bool Utc(string s, out DateTime t) => DateTime.TryParse(s, CultureInfo.InvariantCulture, DateTimeStyles.AdjustToUniversal | DateTimeStyles.AssumeUniversal, out t) && !string.IsNullOrEmpty(s);
    }

    /// <summary>one reading of everything that matters for one USB identity. Error is set (and the lists may be partial) when the PC could not
    /// be read completely: such a snapshot never supports a removal.</summary>
    public sealed class DriverSnapshot
    {
        public string TakenUtc, PcId, StoreKind, HardwareId, Error;
        public List<DeviceBinding> Devices = new List<DeviceBinding>();
        public List<DriverPackage> Packages = new List<DriverPackage>();             // packages that name the identity or are bound to one of its devices
        public Dictionary<string, List<string>> PackageUsers = new Dictionary<string, List<string>>(StringComparer.OrdinalIgnoreCase);   // published name -> every device instance bound to it
        public List<CertificateEntry> Certificates = new List<CertificateEntry>();   // the relevant ones (see Relevant)
        public Dictionary<string, List<string>> CertificateUsers = new Dictionary<string, List<string>>(StringComparer.OrdinalIgnoreCase);   // thumbprint -> packages signed by it
        public bool CertificateScanComplete = true;       // false: some package catalogs could not be read, so sharing is not demonstrated
        public Dictionary<string, string> StoreSummary = new Dictionary<string, string>();   // store -> "count:N sha256:..." of all its thumbprints
        public RestartState Restart = new RestartState();

        public DriverPackage Package(string published) => Packages.FirstOrDefault(p => PinnedDriver.Eq(p.PublishedName, published));
        public List<string> UsersOf(string published) => published != null && PackageUsers.TryGetValue(published, out var l) ? l : new List<string>();
        public bool HasCertificate(CertStore s, string thumbprint) => Certificates.Any(c => c.Store == s && PinnedDriver.Eq(c.Thumbprint, thumbprint));

        /// <summary>a certificate worth recording: anything libwdi or a Workbench setup made (friendly name or subject), anything naming this identity, and
        /// every signer of a relevant package. Root and Trusted Publishers hold many unrelated certificates; only their count and digest are kept.</summary>
        public static bool Relevant(CertificateEntry c, string hardwareId, IEnumerable<string> signers) =>
            (c.Subject ?? "").IndexOf("libwdi", StringComparison.OrdinalIgnoreCase) >= 0 || PinnedDriver.Eq(c.FriendlyName, PinnedDriver.CertificateFriendlyName) || CcsDriver.IsCcsSubject(c.Subject)
            || (c.Subject ?? "").IndexOf(hardwareId.Substring(4), StringComparison.OrdinalIgnoreCase) >= 0 || signers.Any(s => PinnedDriver.Eq(s, c.Thumbprint));

        public JObj ToJson() => new JObj
        {
            { "taken_utc", TakenUtc }, { "pc", PcId ?? "" }, { "store_kind", StoreKind ?? "" }, { "hardware_id", HardwareId ?? "" }, { "error", Error },
            { "devices", Devices.Select(d => d.ToJson()).ToList() }, { "packages", Packages.Select(p => p.ToJson()).ToList() },
            { "package_users", PackageUsers.Select(kv => new JObj { { "package", kv.Key }, { "devices", kv.Value } }).ToList() },
            { "certificates", Certificates.Select(c => c.ToJson()).ToList() },
            { "certificate_users", CertificateUsers.Select(kv => new JObj { { "thumbprint", kv.Key }, { "packages", kv.Value } }).ToList() },
            { "certificate_scan_complete", CertificateScanComplete },
            { "store_summary", StoreSummary.Select(kv => new JObj { { "store", kv.Key }, { "summary", kv.Value } }).ToList() },
            { "restart", Restart.ToJson() },
        };
        public static DriverSnapshot From(Dictionary<string, object> d)
        {
            if (d == null) return null;
            var s = new DriverSnapshot { TakenUtc = d.S("taken_utc"), PcId = d.S("pc"), StoreKind = d.S("store_kind"), HardwareId = d.S("hardware_id"), Error = d.S("error"),
                CertificateScanComplete = d.B("certificate_scan_complete"), Restart = RestartState.From(d.O("restart")) };
            foreach (var o in d.A("devices") ?? new List<object>()) { var x = DeviceBinding.From(o as Dictionary<string, object>); if (x != null) s.Devices.Add(x); }
            foreach (var o in d.A("packages") ?? new List<object>()) { var x = DriverPackage.From(o as Dictionary<string, object>); if (x != null) s.Packages.Add(x); }
            foreach (var o in d.A("certificates") ?? new List<object>()) { var x = CertificateEntry.From(o as Dictionary<string, object>); if (x != null) s.Certificates.Add(x); }
            foreach (var o in (d.A("package_users") ?? new List<object>()).OfType<Dictionary<string, object>>()) s.PackageUsers[o.S("package") ?? ""] = DeviceBinding.Strs(o.A("devices"));
            foreach (var o in (d.A("certificate_users") ?? new List<object>()).OfType<Dictionary<string, object>>()) s.CertificateUsers[o.S("thumbprint") ?? ""] = DeviceBinding.Strs(o.A("packages"));
            foreach (var o in (d.A("store_summary") ?? new List<object>()).OfType<Dictionary<string, object>>()) s.StoreSummary[o.S("store") ?? ""] = o.S("summary") ?? "";
            return s;
        }

        /// <summary>read everything for one identity through a store (reads only). A failure is recorded in Error, never thrown.</summary>
        public static DriverSnapshot Capture(IDriverStore store, ushort vid = PinnedDriver.Vid, ushort pid = PinnedDriver.Pid)
        {
            var s = new DriverSnapshot { TakenUtc = Library.Record.Now(), StoreKind = store.Kind, HardwareId = UsbId.Of(vid, pid) };
            try
            {
                s.PcId = store.PcId;
                s.Devices = store.Devices(vid, pid).Select(x => x.Copy()).ToList();
                var pk = store.Packages(vid, pid).Select(x => x.Copy()).ToList();
                foreach (var d in s.Devices)
                    if (!string.IsNullOrEmpty(d.InfPath) && !pk.Any(p => PinnedDriver.Eq(p.PublishedName, d.InfPath)))
                    { var p = store.Package(d.InfPath); if (p != null) pk.Add(p.Copy()); }
                s.Packages = pk;
                foreach (var p in pk) if (!p.IsInbox) s.PackageUsers[p.PublishedName] = store.DevicesUsing(p.PublishedName).ToList();
                var signers = pk.Select(p => p.SignerThumbprint).Where(t => !string.IsNullOrEmpty(t)).ToList();
                foreach (CertStore cs in Enum.GetValues(typeof(CertStore)))
                {
                    var all = store.Certificates(cs);
                    s.StoreSummary[cs.ToString()] = Summary(all);
                    s.Certificates.AddRange(all.Where(c => Relevant(c, s.HardwareId, signers)).Select(c => CertificateEntry.From(Json.Parse(Json.Write(c.ToJson())))));
                }
                foreach (var t in s.Certificates.Select(c => UsbId.NormThumbprint(c.Thumbprint)).Distinct())
                {
                    var scan = store.PackagesSignedBy(t);
                    s.CertificateUsers[t] = scan.Packages.ToList();
                    if (!scan.Complete) s.CertificateScanComplete = false;
                }
                s.Restart = store.Restart() ?? new RestartState();
            }
            catch (Exception ex) { s.Error = ex.GetType().Name + ": " + ex.Message; }
            return s;
        }

        static string Summary(IReadOnlyList<CertificateEntry> all)
        {
            var t = string.Join("\n", all.Select(c => UsbId.NormThumbprint(c.Thumbprint)).OrderBy(x => x, StringComparer.Ordinal));
            using (var h = System.Security.Cryptography.SHA256.Create()) return "count:" + all.Count + " sha256:" + Hex.Of(h.ComputeHash(System.Text.Encoding.UTF8.GetBytes(t)));
        }
    }

