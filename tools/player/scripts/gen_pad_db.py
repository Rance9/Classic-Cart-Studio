"""Generate the player's table of known controllers (F17, D-99) from the SDL_GameControllerDB mapping file (zlib license; the pinned commit
and its SHA-256 are in tools/player/third_party/sdl_gamecontrollerdb/VENDORED.md). Only Windows entries of USB devices whose GUID carries
the vendor and product ids (03000000 + vendor + 0000 + product + ...) and whose a, b, back and start are buttons are used. The NES pad has
B on the left and A on the right: NES A is the controller's right face button (SDL "b"), NES B its bottom one (SDL "a") (the positions,
so a Nintendo-style pad's A is A). The D-pad comes from the hat and the stick as for every controller, or from buttons when the entry
maps it to buttons.   python gen_pad_db.py <gamecontrollerdb.txt> <out gp_pad_db.h> <out pad-db.json>"""
import json, re, sys
SRC, OUT_H, OUT_J = sys.argv[1:4]
rows = {}
for ln in open(SRC, encoding='utf-8'):
    ln = ln.strip()
    if not ln or ln.startswith('#') or 'platform:Windows' not in ln: continue
    parts = ln.split(','); g = parts[0]
    if not re.fullmatch(r'03000000[0-9a-f]{4}0000[0-9a-f]{4}0000[0-9a-f]{8}', g): continue
    vid = int(g[10:12] + g[8:10], 16); pid = int(g[18:20] + g[16:18], 16)
    m = dict(p.split(':', 1) for p in parts[2:] if ':' in p)
    def btn(k):
        v = m.get(k, ''); return int(v[1:]) if re.fullmatch(r'b\d{1,2}', v) and int(v[1:]) < 32 else None
    a, b, sel, st = btn('b'), btn('a'), btn('back'), btn('start')
    if None in (a, b, sel, st) or len({a, b, sel, st}) < 4: continue
    dirs = [btn('dpup'), btn('dpdown'), btn('dpleft'), btn('dpright')]
    key = (vid, pid)
    if key in rows: continue
    rows[key] = [d if d is not None else -1 for d in dirs] + [a, b, sel, st]
items = sorted(rows.items())
with open(OUT_H, 'w', encoding='utf-8', newline='\n') as f:
    f.write('/* gp_pad_db.h: generated by tools/player/scripts/gen_pad_db.py from SDL_GameControllerDB (zlib license, see\n'
            '   third_party/sdl_gamecontrollerdb). %d controllers by USB vendor and product id: up, down, left, right, A, B, SELECT, START as\n'
            '   input codes (-1: the hat and the stick only). Do not edit by hand. */\n' % len(items))
    f.write('static const struct { unsigned short vid, pid; signed char map[8]; } GP_PAD_DB[] = {\n')
    for (vid, pid), mp in items: f.write('    { 0x%04x, 0x%04x, { %s } },\n' % (vid, pid, ', '.join(str(x) for x in mp)))
    f.write('};\n')
json.dump({'schema': 'ccs-pad-db/1', 'source': 'SDL_GameControllerDB (zlib)', 'count': len(items), 'pads': {f'{vid:04x}-{pid:04x}': mp for (vid, pid), mp in items}}, open(OUT_J, 'w', encoding='utf-8'), separators=(',', ':'))
print(len(items), 'controllers')
