void fb_text(framebuffer *fb, int x, int y, int scale, const char *s, uint8_t r, uint8_t g, uint8_t b) {
    for (const unsigned char *p = (const unsigned char *)s; *p; p++) {
        int c = *p; if (c >= 'a' && c <= 'z') c -= 32; if (c < 32 || c > 95) c = '?';
        const uint8_t *gl = FONT[c - 32];
        for (int col = 0; col < 5; col++) for (int row = 0; row < 7; row++) if (gl[col] & (1 << row)) fb_rect(fb, x + col * scale, y + row * scale, scale, scale, r, g, b);
        x += 6 * scale;
    }
}

uint32_t crc32_bytes(uint32_t seed, const uint8_t *p, size_t n) {
    static uint32_t table[256]; static int init = 0;
    if (!init) { for (uint32_t i = 0; i < 256; i++) { uint32_t c = i; for (int k = 0; k < 8; k++) c = (c & 1) ? 0xEDB88320u ^ (c >> 1) : c >> 1; table[i] = c; } init = 1; }
    uint32_t c = seed ^ 0xFFFFFFFFu; for (size_t i = 0; i < n; i++) c = table[(c ^ p[i]) & 0xFF] ^ (c >> 8); return c ^ 0xFFFFFFFFu;
}

int fb_write_ppm(const framebuffer *fb, const char *path, uint32_t *crc_out) {
    FILE *f = fopen(path, "wb"); if (!f) return -1;
    fprintf(f, "P6\n%d %d\n255\n", fb->w, fb->h);
    size_t n = (size_t)fb->w * fb->h * 3; int ok = fwrite(fb->rgb, 1, n, f) == n; if (fclose(f)) ok = 0;
    if (crc_out) *crc_out = crc32_bytes(0, fb->rgb, n);
    return ok ? 0 : -2;
}
