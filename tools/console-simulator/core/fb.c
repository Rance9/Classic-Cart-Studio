/* Software framebuffer with a 5x7 uppercase font and binary PPM output. This is the diagnostic render path only: a portable
 * CPU buffer the tests can hash. It says nothing about the device's display stack (Mali / HDMI are not modeled). */
#include "ccs_sim.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <ctype.h>

int fb_init(framebuffer *fb, int w, int h) { fb->w = w; fb->h = h; fb->rgb = calloc((size_t)w * h * 3, 1); return fb->rgb ? 0 : -1; }
void fb_free(framebuffer *fb) { free(fb->rgb); fb->rgb = NULL; }
void fb_clear(framebuffer *fb, uint8_t r, uint8_t g, uint8_t b) { for (size_t i = 0, n = (size_t)fb->w * fb->h; i < n; i++) { fb->rgb[i * 3] = r; fb->rgb[i * 3 + 1] = g; fb->rgb[i * 3 + 2] = b; } }
void fb_rect(framebuffer *fb, int x, int y, int w, int h, uint8_t r, uint8_t g, uint8_t b) {
    int x0 = x < 0 ? 0 : x, y0 = y < 0 ? 0 : y, x1 = x + w > fb->w ? fb->w : x + w, y1 = y + h > fb->h ? fb->h : y + h;
    for (int yy = y0; yy < y1; yy++) for (int xx = x0; xx < x1; xx++) { uint8_t *p = fb->rgb + ((size_t)yy * fb->w + xx) * 3; p[0] = r; p[1] = g; p[2] = b; }
}

